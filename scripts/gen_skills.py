#!/usr/bin/env python3
"""Generate the Claude skill, Cursor rule, AGENTS.md template and llms.txt from data/catalog.json.

    python3 scripts/gen_skills.py

data/catalog.json is synced from https://pqblocks.github.io/catalog.json, built from the package
repositories with every quickstart executed. Nothing in the generated files names an API by hand, so an agent that
follows them writes code against the real package.
"""
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SITE = "https://pqblocks.github.io"
SKILL = os.path.join(ROOT, "skills", "pqblocks")
GEN = "<!-- GENERATED by scripts/gen_skills.py from data/catalog.json - do not edit by hand -->"

# task -> package: editorial routing, checked against the catalog below
TASKS = [
    ("ML-KEM / ML-DSA / SLH-DSA primitives (keygen, encapsulate, sign)", "pqblocks-primitives"),
    ("Hybrid ML-KEM-768 + X25519 key establishment, native speed", "pqblocks-core"),
    ("Sign or verify JWTs / JWS with ML-DSA; encrypt JWE with ML-KEM", "pqblocks-jose"),
    ("Encrypt files or byte strings to a post-quantum public key", "pqblocks-files"),
    ("Find RSA / ECC / weak hashes in code or a TLS endpoint; CBOM + SARIF", "pqblocks-scan"),
    ("Python crypto data-flow linting; CBOM + SARIF", "pqblocks-lint"),
    ("Enrich a CycloneDX CBOM with quantum-safety and CNSA 2.0 tags", "pqblocks-cbom"),
    ("Crypto-agility readiness score and CI regression gate", "pqblocks-agility"),
    ("Policy-as-code: fail CI on forbidden algorithms", "pqblocks-policy"),
    ("Audit which JWE / JOSE algorithms a gateway accepts", "pqblocks-jwe-audit"),
    ("CNSA 2.0 compliance evidence pack", "pqblocks-cnsa-evidence"),
    ("Probe a TLS 1.3 endpoint for X25519MLKEM768; hybrid key-schedule checks", "pqblocks-tls-interop"),
    ("Binary container for ML-KEM ciphertexts and ML-DSA / SLH-DSA signatures", "pqblocks-wire"),
    ("Five-part hybrid JWE wire layout (serialise / parse only, no encryption)", "pqblocks-jwe"),
    ("ML-KEM certificate signing request with proof of possession", "pqblocks-csr-pop"),
    ("Run NIST ACVP vectors against ML-KEM / ML-DSA implementations", "pqblocks-acvp"),
    ("Reject malformed or wrong-length FIPS 203/204 inputs at a boundary", "pqblocks-fips-check"),
    ("Build or convert QUBO / Ising models", "pqblocks-qubo"),
    ("Solve QUBO / Ising / Max-Cut (Simulated Bifurcation)", "pqblocks-bifurcation"),
    ("Simulated annealing / quantum annealing / population annealing / QIEA solvers",
     "pqblocks-anneal-sa, pqblocks-anneal-sqa, pqblocks-population-anneal, pqblocks-qiea"),
    ("Benchmark QUBO / Ising solvers (time-to-solution)", "pqblocks-qubo-bench"),
]
RULES = """1. **Use the documented API only.** Before writing code with a PQBlocks package, read its reference file
   below (or call the `get_snippet` tool of the `pqblocks-mcp` server). Every quickstart there was executed
   against the package. Never guess function names.
2. **Never hand-roll post-quantum cryptography.** Use the packages; they wrap maintained implementations
   (liboqs, pyca/cryptography).
3. **Hybrid by default during the transition:** ML-KEM-768 + X25519 for key establishment, ML-DSA-65 +
   Ed25519 for signatures. Downgrade to classical-only must be explicit.
4. **Randomness from the OS only.** Never pass a `seed` argument when generating production keys; seeds
   exist for reproducible tests.
5. **Never log or return secret keys or shared secrets** (logs, exceptions, HTTP responses, `repr`).
6. **Say exactly what is true.** PQBlocks packages implement FIPS 203/204/205 and test against official
   vectors where they exist. They are **not** FIPS 140-3 / CMVP validated, not externally audited, and
   pre-1.0. Never call them certified, validated, audited or quantum-proof.
7. **Quantum-inspired packages are optimisation, not cryptography.** Never place them in a security path.
8. **Install lines:** use the exact install line listed for each package; most install from GitHub
   until their PyPI release is published."""


def short(p):
    return p["package"][len("pqblocks-"):]


def main():
    every = json.load(open(os.path.join(ROOT, "data", "catalog.json"), encoding="utf-8"))["packages"]
    # only verified packages that are not held back; new ones join automatically
    pkgs = [p for p in every if p.get("verified") is True and not p.get("held")]
    by = {p["package"]: p for p in pkgs}

    table = ["| Task | Package | Install | Import |", "|---|---|---|---|"]
    for task, names in TASKS:
        live = [n for n in names.split(", ") if n in by]
        if not live:                          # a routed package that is not published right now
            print("task skipped, no published package: %s" % task)
            continue
        first = by[live[0]]
        pk = ", ".join("[`%s`](reference/%s.md)" % (n, short(by[n])) for n in live)
        table.append("| %s | %s | `%s` | `%s` |" % (task, pk, first["install"], first["import"]))

    os.makedirs(os.path.join(SKILL, "reference"), exist_ok=True)
    for f in os.listdir(os.path.join(SKILL, "reference")):     # a package no longer published loses its file
        if f[:-3] not in {short(p) for p in pkgs}:
            os.remove(os.path.join(SKILL, "reference", f))
    skill = ["---", "name: pqblocks",
             "description: Post-quantum engineering with the PQBlocks packages. Use when adding, migrating or "
             "auditing cryptography for the quantum threat (ML-KEM / FIPS 203, ML-DSA / FIPS 204, SLH-DSA / "
             "FIPS 205, Kyber, Dilithium, hybrid X25519 + ML-KEM), signing or encrypting JWTs post-quantum, "
             "encrypting files post-quantum, finding RSA / ECC in code, producing a CBOM, CNSA 2.0 compliance, "
             "checking TLS for X25519MLKEM768, running NIST ACVP vectors, or solving QUBO / Ising / Max-Cut "
             "problems with quantum-inspired solvers.", "---", "", GEN, "",
             "# PQBlocks: post-quantum engineering", "",
             "PQBlocks is an open-source organisation that builds verified post-quantum (PQ) components: "
             "cryptography, migration and readiness tooling, protocol interoperability, conformance testing and "
             "quantum-inspired optimisation. %d packages, Apache-2.0, docs at %s." % (len(pkgs), SITE), "",
             "## Rules", "", RULES, "",
             "## Which package for which task", "", *table, "",
             "## Migration workflow", "",
             "1. **Discover:** run `pqblocks-scan` on the code base (and `pqblocks-tls-interop` on endpoints).",
             "2. **Assess:** enrich the CBOM with `pqblocks-cbom`; score with `pqblocks-agility`.",
             "3. **Govern:** gate CI with `pqblocks-policy`; build evidence with `pqblocks-cnsa-evidence`.",
             "4. **Migrate:** `pqblocks-primitives` / `pqblocks-core` for primitives, `pqblocks-jose` for tokens, "
             "`pqblocks-files` for files.",
             "5. **Verify:** `pqblocks-acvp` against NIST vectors; `pqblocks-fips-check` at input boundaries.", "",
             "## Reference files", "",
             "Each file holds the package summary, install line, import, command-line entry points and its "
             "executed quickstart. Read the one you need before writing code.", ""]
    skill += ["- [`%s`](reference/%s.md): %s" % (p["package"], short(p), p["summary"]) for p in pkgs]
    open(os.path.join(SKILL, "SKILL.md"), "w").write("\n".join(skill) + "\n")

    for p in pkgs:
        ref = [GEN, "", "# %s" % p["package"], "", p["summary"], ""]
        ref += [l for l in p["intro"]] + [""]
        if p["kind"] == "optimizer":
            ref += ["> Quantum-inspired classical optimisation: not cryptography, no security claim.", ""]
        ref += ["- **Area:** %s" % p["area"], "- **Install:** `%s`" % p["install"], "- **Import:** `import %s`" % p["import"],
                "- **Command line:** %s" % (", ".join("`%s`" % c for c in p["cli"]) or "library only"),
                "- **Native dependency:** %s" % ("liboqs (Open Quantum Safe)" if p["needs_liboqs"] else "none"),
                "- **Status:** %s %s, Python %s" % (p["version"], p["status"], p["python"]),
                "- **Docs:** %s/packages/%s/ · repository %s" % (SITE, short(p), p["url"]), "",
                "## Quickstart (executed against the package)", "", "```python", p["quickstart"].rstrip(), "```", ""]
        if re.search(r"(?:keypair|keygen)\([^)]*\bseed\s*=", p["quickstart"]):
            ref += ["> **Remove `seed=` in production.** It is there for reproducible output; production keys must "
                    "come from the OS random source.", ""]
        if p["examples"]:
            ref += ["## More examples", ""] + ["- %s/blob/main/examples/%s" % (p["url"], e) for e in p["examples"]] + [""]
        ref += ["## Evidence", ""] + ["- [%s](%s)" % (f, u) for f, u in p["docs"].items()]
        open(os.path.join(SKILL, "reference", short(p) + ".md"), "w").write("\n".join(ref) + "\n")

    cursor = ["---", "description: Post-quantum cryptography and quantum-inspired optimisation with PQBlocks packages. "
              "Apply when code touches RSA, ECDSA, ECDH, X25519, JWT signing, key exchange, file encryption, CBOM, "
              "CNSA 2.0, ML-KEM, ML-DSA, SLH-DSA, QUBO or Ising.", "globs:", "alwaysApply: false", "---", "",
              "# PQBlocks", "", RULES.replace("its reference file\n   below", "its page under "
              + SITE + "/packages/"), "", "## Which package for which task", ""]
    cursor += [r.replace("](reference/", "](" + SITE + "/packages/").replace(".md)", "/)") for r in table]
    os.makedirs(os.path.join(ROOT, ".cursor", "rules"), exist_ok=True)
    open(os.path.join(ROOT, ".cursor", "rules", "pqblocks.mdc"), "w").write("\n".join(cursor) + "\n")

    agents = [GEN, "", "# AGENTS.md: post-quantum rules for this project", "",
              "Copy this file into the root of a project (or merge it into an existing AGENTS.md) so coding agents "
              "follow these rules when they touch cryptography.", "", "## Rules", "",
              RULES.replace("its reference file\n   below", "its page under " + SITE + "/packages/"), "",
              "## Which package for which task", ""]
    agents += [r.replace("](reference/", "](" + SITE + "/packages/").replace(".md)", "/)") for r in table]
    agents += ["", "Full catalog for agents: %s/llms.txt (index) and %s/llms-full.txt (with every quickstart)." % (SITE, SITE)]
    open(os.path.join(ROOT, "AGENTS.md"), "w").write("\n".join(agents) + "\n")

    llms = ["# PQBlocks skills", "",
            "> Claude skill, Cursor rule and AGENTS.md template that teach coding agents to use the PQBlocks "
            "post-quantum packages correctly. Generated from the executed package catalog.", "",
            "- [SKILL.md](https://github.com/PQBlocks/pqblocks-skills/blob/main/skills/pqblocks/SKILL.md): Claude skill",
            "- [pqblocks.mdc](https://github.com/PQBlocks/pqblocks-skills/blob/main/.cursor/rules/pqblocks.mdc): Cursor rule",
            "- [AGENTS.md](https://github.com/PQBlocks/pqblocks-skills/blob/main/AGENTS.md): template for any agent",
            "- [Full package catalog for agents](%s/llms-full.txt)" % SITE]
    open(os.path.join(ROOT, "llms.txt"), "w").write("\n".join(llms) + "\n")
    print("SKILL.md + %d reference files, .cursor/rules/pqblocks.mdc, AGENTS.md, llms.txt" % len(pkgs))


if __name__ == "__main__":
    main()
